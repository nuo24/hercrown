// content/devotionals.json → seeds/devotionals.sql with ONLY the approved devotionals (approved: true + approvedBy).
// Then: npm run seed:devotionals (local) / seed:devotionals:staging. Run scripts/check-content.mjs first (npm run check).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const { devotionals } = JSON.parse(readFileSync(`${root}../../content/devotionals.json`, "utf8"));
const approved = devotionals.filter((d) => d.approved === true && d.approvedBy?.trim());
const q = (v) => (typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = approved.map((d, i) => `(${[d.id, i, d.title, d.ref, d.tag, d.minutes, d.body, d.reflection, d.origin, JSON.stringify(d.sources ?? []), d.approvedBy, Date.now()].map(q).join(", ")})`);
writeFileSync(`${root}seeds/devotionals.sql`, [
  "-- Generated by scripts/build-devotionals.mjs from content/devotionals.json (approved entries only). Do not edit by hand.",
  "DELETE FROM devotionals;",
  ...(rows.length ? [`INSERT INTO devotionals (id, position, title, ref, tag, minutes, body, reflection, origin, sources, approved_by, updated_at) VALUES\n${rows.join(",\n")};`] : []),
].join("\n") + "\n");
console.log(`${approved.length} of ${devotionals.length} devotionals approved → seeds/devotionals.sql`);
