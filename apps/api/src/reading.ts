// Reading events (offline-friendly, idempotent uploads) and the streak computed from them.
import { badRequest, readJson } from "./http";
import { preferencesRow, type SessionUser } from "./profile";
import { resolveRef } from "./refs";
import { dayOrdinal, isValidDay, localDayIn, streakSummary } from "./streak";

const MAX_EVENTS = 100;
const ID = /^[A-Za-z0-9_-]{8,64}$/;

export async function readingDays(env: Env, userId: string) {
  const rows = await env.DB.prepare("SELECT DISTINCT local_day FROM reading_events WHERE user_id = ?1")
    .bind(userId)
    .all<{ local_day: string }>();
  return rows.results.map((r) => r.local_day);
}

/** The user's "today": an explicit client day if given, else today in their saved time zone, else UTC. */
export async function resolveToday(env: Env, userId: string, requested: string | null) {
  if (requested) {
    if (!isValidDay(requested)) throw badRequest("today must be a real date in YYYY-MM-DD form");
    return requested;
  }
  const { time_zone } = await preferencesRow(env, userId);
  return localDayIn(time_zone ?? "UTC");
}

/**
 * Body: { events: [{ id, localDay, timeZone, occurredAt?, ref?, planId?, planStep? }], today? }
 * `id` is generated by the client (UUID) so a retried upload never double-counts.
 * Days in the future (beyond the earliest time zone's today) are rejected.
 */
export async function recordReading(request: Request, env: Env, user: SessionUser) {
  const body = await readJson(request);
  const events = body.events;
  if (!Array.isArray(events) || events.length === 0) throw badRequest("events must be a non-empty array");
  if (events.length > MAX_EVENTS) throw badRequest(`At most ${MAX_EVENTS} events per request`);

  const latestAllowed = dayOrdinal(localDayIn("Pacific/Kiritimati")); // UTC+14: the first place a new day starts
  const t = Date.now();
  const statements: D1PreparedStatement[] = [];
  for (const raw of events) {
    const e = (raw ?? {}) as Record<string, unknown>;
    if (typeof e.id !== "string" || !ID.test(e.id)) throw badRequest("Each event needs an id (8-64 letters, digits, - or _)");
    if (typeof e.localDay !== "string" || !isValidDay(e.localDay)) throw badRequest("localDay must be a real date in YYYY-MM-DD form");
    if (dayOrdinal(e.localDay) > latestAllowed) throw badRequest(`localDay ${e.localDay} is in the future`);
    if (typeof e.timeZone !== "string" || !e.timeZone || e.timeZone.length > 64) throw badRequest("timeZone is required");
    const occurredAt = typeof e.occurredAt === "number" && Number.isFinite(e.occurredAt) ? Math.min(e.occurredAt, t) : t;
    const ref = typeof e.ref === "string" ? await resolveRef(env.DB, e.ref) : null;
    const planId = typeof e.planId === "string" ? e.planId.slice(0, 64) : null;
    const planStep = Number.isInteger(e.planStep) ? (e.planStep as number) : null;
    statements.push(
      env.DB.prepare(
        `INSERT OR IGNORE INTO reading_events (id, user_id, local_day, time_zone, occurred_at, ref, plan_id, plan_step, created_at)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?9)`,
      ).bind(e.id, user.id, e.localDay, e.timeZone, occurredAt, ref, planId, planStep, t),
    );
  }
  await env.DB.batch(statements);

  const today = await resolveToday(env, user.id, typeof body.today === "string" ? body.today : null);
  return Response.json({ streak: streakSummary(await readingDays(env, user.id), today) });
}

export async function getStreak(url: URL, env: Env, user: SessionUser) {
  const today = await resolveToday(env, user.id, url.searchParams.get("today"));
  return Response.json({ streak: streakSummary(await readingDays(env, user.id), today) });
}
